"""Validate base, streaming and QNN GPT-SoVITS model bundle interfaces."""

import argparse
from pathlib import Path

import onnx
from onnx import TensorProto, helper

from vits_dynamic import validate_split_reference, validate_vits_interface, validate_vits_masks


BASE_MODELS = (
    "ssl.onnx", "bert.onnx", "g2pW.onnx", "vits.onnx", "t2s_encoder.onnx",
    "t2s_fs_decoder.onnx", "t2s_s_decoder.onnx", "g2p_en/encoder_model.onnx",
    "g2p_en/decoder_model.onnx",
)
QNN_MODELS = ("vits_prefix.onnx", "vits_generator_htp.onnx", "vits_generator_context.onnx")


def check_model_file(path):
    if not path.is_file():
        raise ValueError(f"missing model: {path}")
    try:
        onnx.checker.check_model(str(path))
    except onnx.checker.ValidationError as error:
        if path.parent.name != "g2p_en" or "No Op registered for LayerNormalization" not in str(error):
            raise
        # Some ORT-optimized English G2P exports retain the original opset
        # number after LayerNorm fusion. Check them with their actual runtime.
        import onnxruntime as ort

        try:
            ort.InferenceSession(str(path), providers=["CPUExecutionProvider"])
        except Exception as runtime_error:
            raise ValueError(f"{path}: {runtime_error}") from runtime_error


def checked_model(path, *, load_external_data=False):
    check_model_file(path)
    return onnx.load(path, load_external_data=load_external_data)


def interface(model, inputs, outputs):
    if {v.name for v in model.graph.input} != inputs or {
        v.name for v in model.graph.output
    } != outputs:
        raise ValueError(f"unexpected inputs or outputs for graph {model.graph.name}")
    return {v.name: v.type for v in (*model.graph.input, *model.graph.output)}


def float_shape(info):
    tensor = info.tensor_type
    if tensor.elem_type != TensorProto.FLOAT:
        raise ValueError("expected float32 QNN boundary tensor")
    return [dim.dim_value for dim in tensor.shape.dim]


def validate_qnn(bundle, reference):
    if reference is None:
        raise ValueError("QNN pipeline requires vits_ref.onnx and its CPU decoder")
    prefix = interface(checked_model(bundle / QNN_MODELS[0]),
                       {"text_seq", "pred_semantic", "ge"}, {"z"})
    model = checked_model(bundle / QNN_MODELS[1])
    generator = interface(model, {"z", "ge"}, {"audio"})
    tensors = {tensor.name: tensor.data_type for tensor in model.graph.initializer}
    if not any(
        node.op_type == "DequantizeLinear"
        and tensors.get(node.input[0]) in (TensorProto.UINT8, TensorProto.INT8)
        for node in model.graph.node
    ) or not any(
        node.op_type == "QuantizeLinear" and len(node.input) > 2
        and tensors.get(node.input[2]) in (TensorProto.UINT8, TensorProto.UINT16)
        for node in model.graph.node
    ):
        raise ValueError("QNN VITS generator requires 8-bit weights and QDQ activations")
    if prefix["ge"] != reference.graph.output[0].type or generator["ge"] != prefix["ge"]:
        raise ValueError("QNN generator, prefix and reference disagree on ge")
    latent_shape = float_shape(generator["z"])
    if latent_shape != [1, 192, 128] or float_shape(generator["audio"]) != [128 * 640]:
        raise ValueError("QNN pipeline requires a 128-frame generator with 81920 PCM samples")
    prefix_shape = float_shape(prefix["z"])
    if prefix_shape[:2] != latent_shape[:2] or len(prefix_shape) != 3 or prefix_shape[2] != 0:
        raise ValueError("QNN VITS prefix must produce a dynamic z tensor")
    context_path = bundle / QNN_MODELS[2]
    if not context_path.exists():
        return
    context = checked_model(context_path)
    if interface(context, {"z", "ge"}, {"audio"}) != generator:
        raise ValueError("QNN EPContext interface differs from the generator")
    nodes = list(context.graph.node)
    if len(nodes) != 1 or nodes[0].op_type != "EPContext":
        raise ValueError("expected one QNN EPContext node")
    attributes = {a.name: helper.get_attribute_value(a) for a in nodes[0].attribute}
    if attributes.get("source") != b"QNNExecutionProvider":
        raise ValueError("EPContext was generated by a different execution provider")
    cache = attributes.get("ep_cache_context")
    if not isinstance(cache, bytes) or not cache:
        raise ValueError("missing QNN EPContext binary")
    if attributes.get("embed_mode", 1) == 0:
        relative = Path(cache.decode("utf-8"))
        if relative.is_absolute() or ".." in relative.parts:
            raise ValueError("QNN EPContext must reference a file inside its bundle")
        binary = bundle / relative
        if not binary.is_file() or binary.stat().st_size == 0:
            raise ValueError(f"missing or empty QNN EPContext binary: {binary}")


def validate_bundle(bundle, expect_pro, expect_streaming, expect_ordinary, expect_qnn):
    for name in BASE_MODELS:
        if name != "vits.onnx":
            check_model_file(bundle / name)
    model = checked_model(bundle / "vits.onnx", load_external_data=True)
    inputs = {value.name for value in model.graph.input}
    streaming = "stream_start_frame" in inputs
    if expect_streaming and not streaming:
        raise ValueError("expected a VITS graph with stream_start_frame")
    if streaming and (expect_ordinary or expect_qnn):
        raise ValueError("expected an ordinary CPU VITS graph")
    pro = "sv_emb" in inputs or "ge" in inputs
    if expect_pro and not pro:
        raise ValueError("expected a v2Pro or v2ProPlus VITS interface")
    if pro:
        check_model_file(bundle / "sv.onnx")

    reference = None
    reference_path = bundle / "vits_ref.onnx"
    if "ge" in inputs:
        reference = checked_model(reference_path, load_external_data=True)
        validate_split_reference(reference, model)
    else:
        if reference_path.exists():
            raise ValueError("vits_ref.onnx requires a CPU VITS decoder with a ge input")
        expected = {"text_seq", "pred_semantic", "ref_audio"}
        if pro:
            expected.add("sv_emb")
        validate_vits_interface(model, expected)
        validate_vits_masks(model)

    qnn = expect_qnn or any((bundle / name).exists() for name in QNN_MODELS)
    if qnn:
        validate_qnn(bundle, reference)
    print(f"Verified bundle {bundle} (Pro={pro}, streaming={streaming}, QNN pipeline={qnn})")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bundle-dir", type=Path, required=True)
    parser.add_argument("--expect-v2pro", action="store_true")
    vits_mode = parser.add_mutually_exclusive_group()
    vits_mode.add_argument("--expect-streaming", action="store_true")
    vits_mode.add_argument("--expect-ordinary", action="store_true")
    parser.add_argument("--expect-qnn", action="store_true")
    args = parser.parse_args()
    try:
        validate_bundle(
            args.bundle_dir, args.expect_v2pro, args.expect_streaming,
            args.expect_ordinary, args.expect_qnn,
        )
    except (OSError, ValueError, onnx.checker.ValidationError) as error:
        parser.exit(1, f"Invalid bundle: {error}\n")
